# 🔧 1. Install Django
# If you haven’t installed Django yet:
# #pip install django

# 🏗️ 2. Create a Django Project
# #django-admin startproject myproject
# #cd myproject

# # manage.py – Command-line tool to interact with the project.

# # settings.py – All config settings like DB, installed apps, etc.

# # urls.py – Root URL configuration.

# # wsgi.py/asgi.py – Entry points for deployment.

# ⚙️ 3. Run Development Server
# #python manage.py runserver

# Apps are components/modules of a Django project.
# #python manage.py startapp myapp

