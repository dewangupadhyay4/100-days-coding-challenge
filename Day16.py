def add(num1, num2):
    return num1+num2

def sub(num1, num2):
    return num1-num2

def mul(num1, num2):
    return num1*num2

def div(num1, num2):
    return num1/num2

n1=int(input("Enter the first number: "))
n2=int(input("Enter the second number: "))

print(add(n1,n2))
print(sub(n1,n2))
print(mul(n1,n2))
print(div(n1,n2))